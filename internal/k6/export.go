// Package k6 exports Phoenix scenarios as k6 JavaScript (ES module). The
// output uses inline helpers only (no remote imports) and records everything
// that is not representable in a CompatReport.
package k6

import (
	"bytes"
	"encoding/json"
	"fmt"
	"math"
	"path"
	"regexp"
	"sort"
	"strconv"
	"strings"

	"github.com/lelanga/phoenix/internal/model"
)

// Options tune the export.
type Options struct {
	// DataPrefix is prepended to relative data file paths (path from the
	// script's directory to the scenario's directory), using "/" separators.
	DataPrefix string
}

type exporter struct {
	s     *model.Scenario
	o     Options
	rep   *model.CompatReport
	b     strings.Builder
	ind   int
	notes map[string]bool // notes for the element being written
	// group full path ("::a::b") by transaction/group name
	groups   map[string]string
	reqNames map[string]bool
	files    []string // init-context file declarations
	loopN    int
	abort    bool
	scale    float64
	usesExec bool
}

func js(v any) string {
	return strings.TrimRight(encode(v, ""), "\n")
}

func encode(v any, indent string) string {
	var b bytes.Buffer
	enc := json.NewEncoder(&b)
	enc.SetEscapeHTML(false)
	if indent != "" {
		enc.SetIndent("", indent)
	}
	_ = enc.Encode(v)
	return b.String()
}

func (e *exporter) line(f string, a ...any) {
	e.b.WriteString(strings.Repeat("  ", e.ind))
	e.b.WriteString(fmt.Sprintf(f, a...))
	e.b.WriteByte('\n')
}

func (e *exporter) note(n string) {
	if e.notes == nil {
		e.notes = map[string]bool{}
	}
	e.notes[n] = true
}

var fnRef = regexp.MustCompile(`\$\{(__[A-Za-z]+)`)
var supportedFns = map[string]bool{"__uuid": true, "__randomInt": true, "__randomString": true, "__timestamp": true,
	"__counter": true, "__vu": true, "__iteration": true, "__env": true, "__urlencode": true}

// lit returns a JS string literal for s, noting unsupported functions.
func (e *exporter) lit(s string) string {
	for _, m := range fnRef.FindAllStringSubmatch(s, -1) {
		if !supportedFns[m[1]] {
			e.note("function " + m[1] + " is not available in k6; left unexpanded")
		}
	}
	return js(s)
}

// flush records one report item with the accumulated notes.
func (e *exporter) flush(element, name, loc string, base string) {
	status := base
	if status == "" {
		status = model.Supported
	}
	var notes []string
	for n := range e.notes {
		notes = append(notes, n)
	}
	sort.Strings(notes)
	if len(notes) > 0 && status == model.Supported {
		status = model.Partial
	}
	e.rep.Add(element, name, loc, status, strings.Join(notes, "; "))
	e.notes = nil
}

func ms(d model.Duration) int64 { return d.D().Milliseconds() }

// dur formats a duration as a k6 duration string ("1m30s", "500ms").
func dur(d model.Duration) string {
	t := ms(d)
	if t <= 0 {
		return "0s"
	}
	var b strings.Builder
	if h := t / 3600000; h > 0 {
		fmt.Fprintf(&b, "%dh", h)
		t %= 3600000
	}
	if m := t / 60000; m > 0 {
		fmt.Fprintf(&b, "%dm", m)
		t %= 60000
	}
	if s := t / 1000; s > 0 {
		fmt.Fprintf(&b, "%ds", s)
		t %= 1000
	}
	if t > 0 {
		fmt.Fprintf(&b, "%dms", t)
	}
	return b.String()
}

func num(f float64) string { return strconv.FormatFloat(f, 'f', -1, 64) }

// Export renders s as a k6 script.
func Export(s *model.Scenario, o Options) ([]byte, *model.CompatReport, error) {
	if s == nil {
		return nil, nil, fmt.Errorf("nil scenario")
	}
	if probs := s.Validate(); len(probs) > 0 {
		return nil, nil, fmt.Errorf("scenario is not valid: %s", strings.Join(probs, "; "))
	}
	e := &exporter{s: s, o: o, rep: &model.CompatReport{Source: s.Name, Format: "k6-export"},
		groups: map[string]string{}, reqNames: map[string]bool{}, scale: 1}
	e.abort = s.Workload.OnError == "abort-iteration" || s.Workload.OnError == "stop-vu"
	if s.Workload.ThinkTimeScale != nil {
		e.scale = *s.Workload.ThinkTimeScale
	}
	e.collect(s.Setup, "")
	e.collect(s.Steps, "")
	e.collect(s.Teardown, "")

	// Body first (so file declarations and exec usage are known), then assemble.
	body := e.body()
	var out strings.Builder
	out.WriteString("// Generated by Phoenix Performance (phoenix export-k6) from scenario " + js(s.Name) + ".\n")
	out.WriteString("// Run with: k6 run <this file>. Review the compatibility report for anything approximated.\n")
	out.WriteString("import http from 'k6/http';\nimport { check, sleep, group, fail } from 'k6';\n")
	if len(s.DataSources) > 0 {
		out.WriteString("import { SharedArray } from 'k6/data';\nimport exec from 'k6/execution';\n")
	}
	out.WriteString("\n")
	out.WriteString(e.optionsBlock())
	out.WriteString("\n")
	out.WriteString(e.constants())
	out.WriteString("\n")
	out.WriteString(runtimeJS)
	out.WriteString("\n")
	out.WriteString(body)

	e.rep.Warnings = append(e.rep.Warnings, "k6 runs the generated script against the configured baseUrl; Phoenix's host allowlist does not apply to k6. Only run it against systems you are authorized to test.")
	e.rep.ComputeConfidence()
	e.rep.Validated = "not-run"
	return []byte(out.String()), e.rep, nil
}

// collect records group paths so SLAs scoped to a transaction can be mapped.
func (e *exporter) collect(steps []model.Step, prefix string) {
	for _, st := range steps {
		switch st.Type {
		case model.StepTransaction, model.StepGroup:
			p := prefix + "::" + st.Name
			if _, dup := e.groups[st.Name]; !dup {
				e.groups[st.Name] = p
			}
			e.collect(st.Steps, p)
		case model.StepLoop, model.StepIf:
			e.collect(st.Steps, prefix)
		case model.StepRequest:
			if st.Request != nil {
				e.reqNames[e.reqName(&st)] = true
			}
		}
	}
}

var tagUnsafe = regexp.MustCompile(`[{}",]`)

// reqName is the k6 "name" tag value (kept free of characters that break threshold selectors).
func (e *exporter) reqName(st *model.Step) string {
	n := st.Name
	if n == "" && st.Request != nil {
		n = strings.ToUpper(st.Request.Method) + " " + st.Request.URL
	}
	return tagUnsafe.ReplaceAllString(n, "_")
}

func (e *exporter) optionsBlock() string {
	w := e.s.Workload
	sc := map[string]any{}
	switch w.Executor {
	case model.ExecConstantVUs:
		sc["executor"] = "constant-vus"
		sc["vus"] = w.VUs
		sc["duration"] = dur(w.Duration)
	case model.ExecRampingVUs:
		sc["executor"] = "ramping-vus"
		sc["startVUs"] = w.VUs
		sc["stages"] = e.stages(w.Stages, 1)
	case model.ExecPerVUIterations:
		sc["executor"] = "per-vu-iterations"
		sc["vus"] = w.VUs
		sc["iterations"] = w.Iterations
		md := w.Duration
		if md <= 0 {
			md = model.Duration(3600e9)
			e.note("no duration set; maxDuration defaults to 1h")
		}
		sc["maxDuration"] = dur(md)
	case model.ExecArrivalRate, model.ExecRampingRate:
		pre := w.VUs
		if pre < 1 {
			pre = 1
		}
		mx := w.MaxVUs
		if mx < pre {
			mx = pre
		}
		scale, unit := 1.0, "1s"
		frac := w.Rate != math.Trunc(w.Rate)
		for _, st := range w.Stages {
			frac = frac || st.Target != math.Trunc(st.Target)
		}
		if frac {
			scale, unit = 60, "1m"
			e.note("fractional rates are scaled to iterations per minute (timeUnit 1m)")
		}
		if w.Executor == model.ExecArrivalRate {
			sc["executor"] = "constant-arrival-rate"
			sc["rate"] = math.Round(w.Rate * scale)
			sc["duration"] = dur(w.Duration)
		} else {
			sc["executor"] = "ramping-arrival-rate"
			sc["startRate"] = math.Round(w.Rate * scale)
			sc["stages"] = e.stages(w.Stages, scale)
		}
		sc["timeUnit"] = unit
		sc["preAllocatedVUs"] = pre
		sc["maxVUs"] = mx
	}
	if w.GracefulStop > 0 {
		sc["gracefulStop"] = dur(w.GracefulStop)
	}
	sc["exec"] = "default"
	e.flush("workload", w.Executor, "workload", "")
	opts := map[string]any{"scenarios": map[string]any{"phoenix": sc}}
	if e.s.Defaults.InsecureSkipVerify {
		opts["insecureSkipTLSVerify"] = true
	}
	th := e.thresholds()
	if len(th) > 0 {
		opts["thresholds"] = th
	}
	return "export const options = " + strings.TrimRight(encode(opts, "  "), "\n") + ";\n"
}

func (e *exporter) stages(st []model.Stage, scale float64) []map[string]any {
	var out []map[string]any
	for _, s := range st {
		out = append(out, map[string]any{"duration": dur(s.Duration), "target": math.Round(s.Target * scale)})
	}
	return out
}

func (e *exporter) thresholds() map[string][]string {
	th := map[string][]string{}
	for i, sla := range e.s.SLAs {
		loc := fmt.Sprintf("slas[%d]", i)
		label := sla.Metric
		sel := ""
		if sla.Scope != "" {
			label += " @" + sla.Scope
			switch {
			case e.groups[sla.Scope] != "":
				if strings.ContainsAny(sla.Scope, "{},\"") {
					e.rep.Add("sla", label, loc, model.Unsupported, "scope name contains characters k6 threshold selectors cannot express")
					continue
				}
				sel = "{group:" + e.groups[sla.Scope] + "}"
			case e.reqNames[tagUnsafe.ReplaceAllString(sla.Scope, "_")]:
				sel = "{name:" + tagUnsafe.ReplaceAllString(sla.Scope, "_") + "}"
				if tagUnsafe.MatchString(sla.Scope) {
					e.note("request name contained { } , or quotes; replaced by _ in the k6 name tag")
				}
			default:
				e.rep.Add("sla", label, loc, model.Unsupported, "scope matches no transaction or request name")
				continue
			}
		}
		var metric, expr string
		switch sla.Metric {
		case "p50", "p90", "p95", "p99":
			metric, expr = "http_req_duration", "p("+sla.Metric[1:]+")"+sla.Op+num(sla.Threshold)
		case "avg", "max":
			metric, expr = "http_req_duration", sla.Metric+sla.Op+num(sla.Threshold)
		case "error_rate":
			metric, expr = "http_req_failed", "rate"+sla.Op+num(sla.Threshold/100)
			e.note("k6 http_req_failed counts HTTP failures only; failed Phoenix assertions appear in the checks metric")
		case "rps":
			metric, expr = "http_reqs", "rate"+sla.Op+num(sla.Threshold)
		default:
			e.rep.Add("sla", label, loc, model.Unsupported, "metric "+sla.Metric+" has no k6 equivalent")
			continue
		}
		th[metric+sel] = append(th[metric+sel], expr)
		e.flush("sla", label, loc, "")
	}
	return th
}

func (e *exporter) constants() string {
	s := e.s
	var b strings.Builder
	d := s.Defaults
	vars := map[string]string{}
	for k, v := range s.Variables {
		vars[k] = v
	}
	b.WriteString("const VARS = " + js(vars) + ";\n")
	b.WriteString("const BASE_URL = " + e.lit(d.BaseURL) + ";\n")
	hs := [][2]string{}
	for _, h := range d.Headers {
		hs = append(hs, [2]string{h.Name, h.Value})
		e.lit(h.Value)
	}
	b.WriteString("const DEFAULT_HEADERS = " + js(hs) + ";\n")
	b.WriteString("const DEFAULT_TIMEOUT = " + strconv.FormatInt(ms(d.Timeout), 10) + ";\n")
	if d.FollowRedirects != nil && !*d.FollowRedirects {
		b.WriteString("const DEFAULT_REDIRECTS = 0;\n")
	} else {
		b.WriteString("const DEFAULT_REDIRECTS = undefined;\n")
	}
	b.WriteString("const NO_COOKIES = " + strconv.FormatBool(d.DisableCookies) + ";\n")
	if d.MaxBodyBytes > 0 {
		e.note("defaults.maxBodyBytes has no k6 equivalent (use discardResponseBodies/responseType per request if needed)")
	}
	e.flush("defaults", "", "defaults", "")
	for k := range s.Variables {
		e.lit(s.Variables[k])
	}
	e.flush("variables", fmt.Sprintf("%d variables", len(s.Variables)), "variables", "")
	for _, ds := range s.DataSources {
		b.WriteString(e.dataSource(ds))
	}
	for _, f := range e.files {
		b.WriteString(f)
	}
	return b.String()
}

func (e *exporter) dataSource(ds model.DataSource) string {
	loc := "dataSources." + ds.Name
	name := "DS_" + ident(ds.Name)
	delim := ds.Delimiter
	if delim == "" {
		delim = ","
	}
	cols := "null"
	if len(ds.Columns) > 0 {
		cols = js(ds.Columns)
	}
	var init string
	if ds.File != "" {
		p := ds.File
		if !path.IsAbs(p) && e.o.DataPrefix != "" {
			p = path.Join(e.o.DataPrefix, p)
		}
		init = "_csv(open(" + js(p) + "), " + js(delim) + ", " + cols + ")"
		e.note("open() resolves " + p + " relative to the script; keep the CSV at that path")
	} else {
		init = "_rows(" + js(ds.Rows) + ", " + cols + ")"
	}
	switch ds.Mode {
	case "unique", "sequential", "":
		e.note("k6 has no shared cursor; rows follow the scenario-wide iteration counter (exec.scenario.iterationInTest)")
	}
	if ds.OnExhaust == "stop" {
		e.note("onExhaust=stop ends the iteration quietly; k6 VUs cannot be stopped individually")
	}
	if ds.Sensitive {
		e.note("sensitive masking is not applied by k6")
	}
	e.flush("dataSource", ds.Name, loc, "")
	return "const " + name + " = new SharedArray(" + js(ds.Name) + ", function () { return " + init + "; });\n"
}

var identRe = regexp.MustCompile(`[^A-Za-z0-9_]+`)

func ident(s string) string { return identRe.ReplaceAllString(s, "_") }
